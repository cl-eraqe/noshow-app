// Two regional-indicator letters render as the country's flag emoji.
function flagEmoji(iso2) {
  return String.fromCodePoint(...[...iso2.toUpperCase()].map(c => 0x1F1A5 + c.charCodeAt(0)));
}

// "🇵🇰 PAK" for a known nationality; the name upper-cased otherwise, so an
// unexpected entry still reads instead of vanishing.
function nationalityLabel(nat) {
  const name = String(nat || '').trim();
  const iso2 = NATIONALITY_ISO2[name];
  if (!iso2) return name ? name.toUpperCase() : '???';
  return `${flagEmoji(iso2)} ${ISO3[iso2]}`;
}

